const DICTS: Record<Lang, Record<string, string>> = { en, id };

export function translate(lang: Lang, key: string, params?: Record<string, string>): string {
  const template = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => params[name] ?? "");
}

const I18nContext = createContext<{ lang: Lang; t: T }>({
  lang: "en",
  t: (key, params) => translate("en", key, params),
});

export function I18nProvider({
  lang,
  children,
}: {
  lang: Lang;
  children: ComponentChildren;
}) {
  const t: T = (key, params) => translate(lang, key, params);
  return <I18nContext.Provider value={{ lang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): { lang: Lang; t: T } {
  return useContext(I18nContext);
}
